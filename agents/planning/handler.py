"""
Planning Agent Lambda Handler.

The Planning Agent acts as the Technical Lead:
1. Reads architecture knowledge from S3.
2. Generates an Engineering Contract (change classification, intent, constraints).
3. Searches the target GitHub repository for relevant files.
4. Downloads top candidate files.
5. Asks the LLM to produce an implementationContract with exact file paths,
   operations (MODIFY/CREATE), protected files, and validation checklist.

The Development Agent consumes the implementationContract as an Implementer.

Input: Workflow event from Step Functions containing ticket information.
Output: Workflow event enriched with 'planning' and status 'PLANNED'.
"""

import re
from decimal import Decimal
from hashlib import sha256
from typing import Any

from shared.bedrock_client import BedrockClient
from shared.config import PlanningConfig
from shared.dynamodb_helper import WorkflowTable
from shared.github_client import GitHubClient
from shared.logger import get_logger
from shared.prompts import planning as prompts
from shared.s3_helper import S3Helper

logger = get_logger(__name__, agent="planning")

# Maximum candidate files to download from the repository
MAX_CANDIDATE_FILES = 10

# Maximum files whose content is sent to the LLM for contract generation
MAX_FILES_FOR_CONTRACT = 5

# Valid values for enum-like fields (used for validation/defaults)
VALID_CHANGE_TYPES = {
    "BUG_FIX",
    "NEW_FEATURE",
    "ENHANCEMENT",
    "REFACTOR",
    "CONFIGURATION",
    "DOCUMENTATION",
}
VALID_RISK_LEVELS = {"LOW", "MEDIUM", "HIGH"}
VALID_SCOPES = {"SMALL", "MEDIUM", "LARGE"}


# ---------------------------------------------------------------------------
# Architecture knowledge
# ---------------------------------------------------------------------------


def _load_architecture_knowledge(s3: S3Helper) -> dict[str, Any] | None:
    """
    Load the architecture knowledge base from S3.

    This is the JSON generated by the Architecture Agent.
    Returns None if not available (first run, or architecture agent hasn't run yet).
    """
    try:
        if s3.object_exists("architecture/knowledge.json"):
            knowledge = s3.download_json("architecture/knowledge.json")
            logger.info("Architecture knowledge loaded from S3")
            return knowledge
    except Exception as ex:
        logger.warning("Could not load architecture knowledge", error=str(ex))

    return None


# ---------------------------------------------------------------------------
# Keyword extraction
# ---------------------------------------------------------------------------


def _extract_keywords(event: dict[str, Any]) -> list[str]:
    """
    Extract search keywords from the ticket.

    Sources:
        - Ticket summary
        - Ticket description
        - Architecture knowledge module names (if available in planning)

    Returns:
        Deduplicated list of keywords (lowercased, min 3 chars).
    """
    keywords: set[str] = set()

    stop_words = {
        "the",
        "and",
        "for",
        "from",
        "with",
        "this",
        "that",
        "have",
        "has",
        "are",
        "was",
        "were",
        "been",
        "being",
        "will",
        "would",
        "could",
        "should",
        "can",
        "may",
        "might",
        "shall",
        "not",
        "but",
        "its",
        "into",
        "over",
        "under",
        "between",
        "change",
        "update",
        "add",
        "remove",
        "fix",
        "implement",
        "create",
        "delete",
        "modify",
        "please",
        "need",
        "want",
        "text",
        "page",
    }

    # From ticket summary
    summary = event.get("summary", "")
    words = re.findall(r"[a-zA-Z]+", summary)
    for word in words:
        w = word.lower()
        if len(w) >= 3 and w not in stop_words:
            keywords.add(w)

    # From ticket description
    description = event.get("description", "")
    desc_words = re.findall(r"[a-zA-Z]+", description)
    for word in desc_words:
        w = word.lower()
        if len(w) >= 3 and w not in stop_words:
            keywords.add(w)

    return list(keywords)


# ---------------------------------------------------------------------------
# Repository search
# ---------------------------------------------------------------------------


def _search_repository(
    github: GitHubClient,
    keywords: list[str],
    candidate_modules: list[str],
    expected_file_types: list[str],
) -> list[str]:
    """
    Search the repository for relevant files using keywords and module names.

    Combines keyword search results with module-based search.

    Args:
        github: Initialized GitHubClient.
        keywords: Keywords extracted from the ticket.
        candidate_modules: Logical module names from the Engineering Contract.
        expected_file_types: Expected file extensions from the Engineering Contract.

    Returns:
        Deduplicated list of candidate file paths (max MAX_CANDIDATE_FILES).
    """
    # Combine keywords with candidate module names for broader search
    all_keywords = list(keywords)
    for module in candidate_modules:
        module_parts = re.findall(r"[a-zA-Z]+", module)
        for part in module_parts:
            if len(part) >= 3 and part.lower() not in all_keywords:
                all_keywords.append(part.lower())

    # Search by keywords
    search_results = github.search_files_by_keywords(
        keywords=all_keywords,
        max_results=MAX_CANDIDATE_FILES,
    )

    candidate_paths = [r["path"] for r in search_results]

    # If we have expected file types, also search by extension to widen the net
    if expected_file_types and len(candidate_paths) < MAX_CANDIDATE_FILES:
        extensions = [f".{ext.lstrip('.')}" for ext in expected_file_types]
        for module in candidate_modules:
            module_lower = module.lower()
            ext_results = github.find_files(extensions=extensions, contains=module_lower)
            for path in ext_results:
                if path not in candidate_paths:
                    candidate_paths.append(path)
                if len(candidate_paths) >= MAX_CANDIDATE_FILES:
                    break
            if len(candidate_paths) >= MAX_CANDIDATE_FILES:
                break

    logger.info(
        "Repository search complete",
        keyword_count=len(all_keywords),
        candidates_found=len(candidate_paths),
        candidates=candidate_paths[:MAX_CANDIDATE_FILES],
    )

    return candidate_paths[:MAX_CANDIDATE_FILES]


# ---------------------------------------------------------------------------
# Download candidate files
# ---------------------------------------------------------------------------


def _download_candidates(
    github: GitHubClient,
    candidate_paths: list[str],
) -> tuple[dict[str, str], dict[str, str]]:
    """
    Download content of the top candidate files and compute SHA256 hashes.

    Only downloads up to MAX_FILES_FOR_CONTRACT files to keep
    the LLM context manageable.

    Args:
        github: Initialized GitHubClient.
        candidate_paths: List of file paths to download.

    Returns:
        Tuple of (path -> file content, path -> SHA256 hex digest).
    """
    paths_to_download = candidate_paths[:MAX_FILES_FOR_CONTRACT]
    logger.info(
        "Downloading candidate files for contract",
        file_count=len(paths_to_download),
        files=paths_to_download,
    )
    contents = github.get_multiple_files(paths_to_download)

    # Compute SHA256 for each downloaded file
    hashes: dict[str, str] = {}
    for path, content in contents.items():
        hashes[path] = sha256(content.encode("utf-8")).hexdigest()

    logger.info("SHA256 hashes computed", file_count=len(hashes))

    return contents, hashes


# ---------------------------------------------------------------------------
# Implementation contract generation
# ---------------------------------------------------------------------------


def _generate_implementation_contract(
    bedrock: BedrockClient,
    event: dict[str, Any],
    planning: dict[str, Any],
    candidate_paths: list[str],
    file_contents: dict[str, str],
    file_hashes: dict[str, str],
    architecture_knowledge: dict[str, Any] | None,
) -> dict[str, Any]:
    """
    Ask the LLM to produce an implementationContract with exact file decisions.

    The LLM receives the ticket, Engineering Contract, candidate files and their
    content, and returns precise MODIFY/CREATE decisions per file.

    After generation, enriches each file entry with:
    - confidence: LLM's confidence score (or default 0.9)
    - sha256: hash of the file at the time of planning (for MODIFY operations)

    Args:
        bedrock: Initialized BedrockClient.
        event: Workflow event with ticket info.
        planning: Engineering Contract (first LLM pass).
        candidate_paths: All candidate file paths found in the repo.
        file_contents: Downloaded file contents (path -> content).
        file_hashes: SHA256 hashes of downloaded files (path -> hex digest).
        architecture_knowledge: Architecture knowledge from S3.

    Returns:
        implementationContract dict, or a fallback if LLM call fails.
    """
    try:
        contract = bedrock.converse_json(
            system_prompt=prompts.implementation_contract_system_prompt(),
            user_prompt=prompts.implementation_contract_user_prompt(
                workflow=event,
                planning=planning,
                candidate_paths=candidate_paths,
                file_contents=file_contents,
                architecture_knowledge=architecture_knowledge,
            ),
            max_tokens=4096,
            temperature=0.1,
        )

        # Validate structure
        contract = _validate_implementation_contract(contract)

        # Enrich each file with confidence and SHA256
        contract = _enrich_contract_files(contract, file_hashes)

        logger.info(
            "Implementation contract generated",
            file_count=len(contract.get("files", [])),
            protected_count=len(contract.get("protectedFiles", [])),
        )

        return contract

    except Exception as ex:
        logger.warning(
            "Implementation contract generation failed, using fallback",
            error=str(ex),
        )
        return _build_fallback_contract(planning, candidate_paths, file_hashes)


def _validate_implementation_contract(contract: dict[str, Any]) -> dict[str, Any]:
    """
    Validate and normalize the implementationContract from the LLM.

    Ensures required fields exist with correct types.
    """
    # Ensure top-level fields
    if not isinstance(contract.get("files"), list):
        contract["files"] = []

    if not isinstance(contract.get("protectedFiles"), list):
        contract["protectedFiles"] = []

    if not isinstance(contract.get("allowedOperations"), list):
        contract["allowedOperations"] = ["MODIFY", "CREATE"]

    if not isinstance(contract.get("validationChecklist"), list):
        contract["validationChecklist"] = []

    # Validate each file entry
    validated_files: list[dict[str, Any]] = []
    for entry in contract["files"]:
        if not isinstance(entry, dict):
            continue
        if not entry.get("path"):
            continue
        if entry.get("operation") not in ("MODIFY", "CREATE"):
            entry["operation"] = "MODIFY"
        if not isinstance(entry.get("reason"), str):
            entry["reason"] = ""
        if not isinstance(entry.get("expectedChanges"), list):
            entry["expectedChanges"] = []
        validated_files.append(entry)

    contract["files"] = validated_files
    return contract


def _enrich_contract_files(
    contract: dict[str, Any],
    file_hashes: dict[str, str],
) -> dict[str, Any]:
    """
    Enrich each file in the contract with confidence and SHA256 hash.

    - confidence: Uses the LLM-provided value if present, otherwise defaults to 0.9.
    - sha256: The hash of the file content at the time of planning.
      Only set for MODIFY operations (file must already exist).
      Allows the Development Agent to detect if the file changed
      between planning and implementation.

    Args:
        contract: Validated implementation contract.
        file_hashes: SHA256 hashes from downloaded files (path -> hex digest).

    Returns:
        Enriched contract.
    """
    for file_entry in contract.get("files", []):
        # Confidence: keep LLM value if valid, otherwise default
        if not isinstance(file_entry.get("confidence"), (int, float)):
            file_entry["confidence"] = 0.9

        # SHA256: attach hash for MODIFY operations so the Development Agent
        # can verify the file hasn't changed before modifying it
        path = file_entry.get("path", "")
        if file_entry.get("operation") == "MODIFY" and path in file_hashes:
            file_entry["sha256"] = file_hashes[path]
        elif file_entry.get("operation") == "CREATE":
            file_entry["sha256"] = None
        else:
            # MODIFY but file wasn't downloaded (edge case)
            file_entry["sha256"] = None

    return contract


def _build_fallback_contract(
    planning: dict[str, Any],
    candidate_paths: list[str],
    file_hashes: dict[str, str] | None = None,
) -> dict[str, Any]:
    """
    Build a fallback implementationContract from the Engineering Contract.

    Used when the LLM contract generation call fails.
    """
    file_hashes = file_hashes or {}
    files: list[dict[str, Any]] = []

    # Use filesToGenerate from the engineering contract as a base
    for path in planning.get("filesToGenerate", []):
        operation = "MODIFY" if path in candidate_paths else "CREATE"
        files.append(
            {
                "path": path,
                "operation": operation,
                "reason": "From engineering contract filesToGenerate",
                "expectedChanges": planning.get("expectedChanges", []),
                "confidence": 0.7,
                "sha256": file_hashes.get(path) if operation == "MODIFY" else None,
            }
        )

    return {
        "files": files,
        "protectedFiles": planning.get("mustNotChange", []),
        "allowedOperations": ["MODIFY", "CREATE"],
        "validationChecklist": planning.get("validationChecklist", []),
    }


# ---------------------------------------------------------------------------
# Engineering Contract validation
# ---------------------------------------------------------------------------


def _validate_engineering_contract(planning: dict[str, Any]) -> dict[str, Any]:
    """
    Validate and normalize Engineering Contract fields.

    Ensures all new fields exist with correct types and valid enum values.
    Falls back to sensible defaults if the LLM returned unexpected values.
    """
    # Validate changeType
    change_type = planning.get("changeType", "")
    if change_type not in VALID_CHANGE_TYPES:
        planning["changeType"] = "ENHANCEMENT"
        logger.warning(
            "Invalid changeType from LLM, defaulting to ENHANCEMENT",
            raw_value=change_type,
        )

    # Validate intent (must be a non-empty string)
    if not isinstance(planning.get("intent"), str) or not planning["intent"].strip():
        planning["intent"] = planning.get("summary", "")

    # Validate list fields — ensure they are lists
    list_fields = [
        "candidateModules",
        "expectedFileTypes",
        "avoidFileTypes",
        "expectedChanges",
        "mustNotChange",
        "validationChecklist",
    ]
    for field in list_fields:
        if not isinstance(planning.get(field), list):
            planning[field] = []

    # Validate riskLevel
    risk_level = planning.get("riskLevel", "")
    if risk_level not in VALID_RISK_LEVELS:
        planning["riskLevel"] = "MEDIUM"
        logger.warning(
            "Invalid riskLevel from LLM, defaulting to MEDIUM",
            raw_value=risk_level,
        )

    # Validate estimatedScope
    scope = planning.get("estimatedScope", "")
    if scope not in VALID_SCOPES:
        planning["estimatedScope"] = "MEDIUM"
        logger.warning(
            "Invalid estimatedScope from LLM, defaulting to MEDIUM",
            raw_value=scope,
        )

    return planning


# ---------------------------------------------------------------------------
# Fallback plan
# ---------------------------------------------------------------------------


def _build_fallback_plan(event: dict[str, Any], error: str) -> dict[str, Any]:
    """
    Build a fallback planning dict when Bedrock call fails.

    Includes both legacy fields and new Engineering Contract fields
    to maintain backward compatibility.
    """
    return {
        # Legacy fields
        "summary": event.get("summary", ""),
        "requirements": [],
        "acceptanceCriteria": [],
        "implementationPlan": [],
        "testCases": [],
        "affectedModules": [],
        "technologies": [],
        "filesToGenerate": [],
        # Engineering Contract fields
        "changeType": "ENHANCEMENT",
        "intent": event.get("summary", ""),
        "candidateModules": [],
        "expectedFileTypes": [],
        "avoidFileTypes": [],
        "expectedChanges": [],
        "mustNotChange": [],
        "validationChecklist": [],
        "riskLevel": "MEDIUM",
        "estimatedScope": "MEDIUM",
        # Implementation Contract (empty fallback)
        "implementationContract": {
            "files": [],
            "protectedFiles": [],
            "allowedOperations": ["MODIFY", "CREATE"],
            "validationChecklist": [],
        },
        # Metadata
        "confidence": Decimal("0.50"),
        "estimatedFiles": 0,
        "error": error,
    }


# ---------------------------------------------------------------------------
# Main handler
# ---------------------------------------------------------------------------


def lambda_handler(event: dict[str, Any], context: Any) -> dict[str, Any]:
    """Planning agent entry point."""
    logger.info("Planning agent started", workflow_id=event.get("workflowId"))

    config = PlanningConfig()
    workflow_id = event.get("workflowId")

    if not workflow_id:
        raise ValueError(f"workflowId missing from event: {event}")

    # Initialize services
    bedrock = BedrockClient(config.bedrock_model_id)
    s3 = S3Helper(config.s3_bucket)
    table = WorkflowTable(config.table_name)
    github = GitHubClient(
        owner=config.github_repo_owner,
        repo=config.github_repo_name,
        secret_name=config.github_secret_name,
    )

    # Load architecture knowledge base (generated by architecture agent)
    architecture_knowledge = _load_architecture_knowledge(s3)

    # -----------------------------------------------------------------------
    # Phase 1: Generate Engineering Contract
    # -----------------------------------------------------------------------
    try:
        planning = bedrock.converse_json(
            system_prompt=prompts.system_prompt(),
            user_prompt=prompts.user_prompt(
                workflow=event,
                architecture_knowledge=architecture_knowledge,
            ),
            max_tokens=4096,
        )

        # Validate and normalize Engineering Contract fields
        planning = _validate_engineering_contract(planning)

        # Enrich with confidence metrics
        planning["confidence"] = Decimal("0.95")
        planning["estimatedFiles"] = max(
            len(planning.get("filesToGenerate", [])),
            len(planning.get("affectedModules", [])) * 2,
            1,
        )

        logger.info(
            "Engineering Contract generated",
            workflow_id=workflow_id,
            change_type=planning.get("changeType"),
            risk_level=planning.get("riskLevel"),
            estimated_scope=planning.get("estimatedScope"),
            candidate_modules=planning.get("candidateModules"),
            files_to_generate=len(planning.get("filesToGenerate", [])),
            confidence=str(planning["confidence"]),
        )

    except Exception as ex:
        logger.error("Plan generation failed, using fallback", error=str(ex))
        planning = _build_fallback_plan(event, str(ex))

        # Persist fallback and return early
        table.update_status(workflow_id=workflow_id, status="PLANNED", planning=planning)
        s3.upload_json(f"plans/{workflow_id}.json", planning)
        event["planning"] = planning
        event["status"] = "PLANNED"
        return event

    # -----------------------------------------------------------------------
    # Phase 2: Search repository for relevant files
    # -----------------------------------------------------------------------
    keywords = _extract_keywords(event)
    logger.info("Keywords extracted for repo search", keywords=keywords)

    candidate_paths = _search_repository(
        github=github,
        keywords=keywords,
        candidate_modules=planning.get("candidateModules", []),
        expected_file_types=planning.get("expectedFileTypes", []),
    )

    # Download top candidate files
    file_contents, file_hashes = _download_candidates(github, candidate_paths)
    logger.info(
        "Candidate files downloaded",
        downloaded_count=len(file_contents),
    )

    # -----------------------------------------------------------------------
    # Phase 3: Generate Implementation Contract
    # -----------------------------------------------------------------------
    implementation_contract = _generate_implementation_contract(
        bedrock=bedrock,
        event=event,
        planning=planning,
        candidate_paths=candidate_paths,
        file_contents=file_contents,
        file_hashes=file_hashes,
        architecture_knowledge=architecture_knowledge,
    )

    # Attach implementation contract to the planning output
    planning["implementationContract"] = implementation_contract

    # Update filesToGenerate for backward compatibility only.
    # The Development Agent should consume implementationContract instead.
    contract_files = [f["path"] for f in implementation_contract.get("files", []) if f.get("path")]
    if contract_files:
        planning["filesToGenerate"] = contract_files

    # -----------------------------------------------------------------------
    # Persist and return
    # -----------------------------------------------------------------------
    table.update_status(
        workflow_id=workflow_id,
        status="PLANNED",
        planning=planning,
    )

    # Store plan artifact in S3
    s3.upload_json(f"plans/{workflow_id}.json", planning)

    # Enrich workflow event for next step
    event["planning"] = planning
    event["status"] = "PLANNED"

    logger.info(
        "Planning complete with implementation contract",
        workflow_id=workflow_id,
        contract_files=len(contract_files),
        protected_files=len(implementation_contract.get("protectedFiles", [])),
    )

    return event
